/**
 * Synchronize generated deployment consumers from the canonical Base manifest.
 * This is safe to run before local builds; promotion runs the equivalent write
 * after it has validated a candidate deployment on-chain.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const canonicalPath = join(root, "contracts", "deployments", "base-8453.json");
const microPath = join(root, "contracts", "deployments", "base-8453-micro.json");
const manifest = JSON.parse(await readFile(canonicalPath, "utf8"));
const micro = JSON.parse(await readFile(microPath, "utf8"));
if (manifest.market !== "standard" || micro.market !== "micro") {
  throw new Error("canonical manifests must declare standard and micro markets");
}
if (String(manifest.chainId) !== "8453" || String(micro.chainId) !== "8453") {
  throw new Error("canonical manifests must target Base chain 8453");
}
if (manifest.external?.azl?.toLowerCase() !== micro.external?.azl?.toLowerCase()) {
  throw new Error("standard and micro manifests must share the AZL payment token");
}

const generated = () =>
  `// GENERATED by scripts/sync-manifest-surfaces.mjs. Do not edit.\n` +
  `export const BASE_MAINNET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n` +
  `export const BASE_MAINNET_MICRO_MANIFEST = ${JSON.stringify(micro, null, 2)} as const;\n` +
  `export const BASE_MAINNET_MANIFESTS = {\n` +
  `  standard: BASE_MAINNET_MANIFEST,\n` +
  `  micro: BASE_MAINNET_MICRO_MANIFEST,\n` +
  `} as const;\n\n` +
  `export type AzzleMarket = keyof typeof BASE_MAINNET_MANIFESTS;\n\n` +
  `export function selectBaseMainnetManifest(market: AzzleMarket) {\n` +
  `  return BASE_MAINNET_MANIFESTS[market];\n` +
  `}\n`;
const browserGenerated =
  `// GENERATED by contracts/scripts/promote-manifest.ts. Do not edit.\n` +
  `export const MANIFESTS = {\n` +
  `  standard: ${JSON.stringify(manifest, null, 2)},\n` +
  `  micro: ${JSON.stringify(micro, null, 2)}\n` +
  `};\n` +
  `export const MANIFEST = MANIFESTS.standard;\n` +
  "export const AZL_TOKEN = MANIFEST.external.azl;\n";

const x402Path = join(root, "agents", "x402-cloud", "bankr.x402.json");
const x402 = JSON.parse(await readFile(x402Path, "utf8"));
for (const service of Object.values(x402.services ?? {})) service.tokenAddress = manifest.external.azl;

const outputs = new Map([
  [join(root, "agents", "deployments", "base-8453.json"), JSON.stringify(manifest, null, 2) + "\n"],
  [join(root, "api", "lib", "contracts.json"), JSON.stringify(manifest, null, 2) + "\n"],
  [join(root, "agents", "deployments", "base-8453-micro.json"), JSON.stringify(micro, null, 2) + "\n"],
  [join(root, "api", "lib", "contracts-micro.json"), JSON.stringify(micro, null, 2) + "\n"],
  [join(root, "agents", "x402-cloud", "x402", "manifest.ts"), generated()],
  [join(root, "launch-skills", "js", "manifest.generated.js"), browserGenerated],
  [x402Path, JSON.stringify(x402, null, 2) + "\n"],
]);
if (checkOnly) {
  const stale = [];
  for (const [file, expected] of outputs) {
    try {
      if (await readFile(file, "utf8") !== expected) stale.push(file);
    } catch {
      stale.push(file);
    }
  }
  if (stale.length) throw new Error(`[manifest] stale generated consumers:\n${stale.join("\n")}`);
  console.log("[manifest] generated dual-market consumers are current");
} else {
  await Promise.all([...outputs].map(([file, content]) => writeFile(file, content)));
  console.log("[manifest] generated consumers synchronized from both Base market manifests");
}
